def block(src, start, end):
    i = src.index(start)
    return src[i:src.index(end, i) + len(end)]


def relink(s, up):
    """Ссылки главной → ссылки со страницы на глубине up (../ * up)."""
    p = '../' * up
    s = re.sub(r'href="#"', f'href="{p}"', s)
    s = re.sub(r'href="#([^"]*)"', rf'href="{p}#\1"', s)
    return re.sub(r'href="(kontakty/|dokumenty/|uslugi/|ceny/)', rf'href="{p}\1', s)


def page(src, up, title, desc, path, body):
    head = block(src, '<!doctype html>', '<style>')[:-len('<style>')]
    head = re.sub(r'<title>.*?</title>', f'<title>{e(title)} — {BRAND}</title>', head)
    head = re.sub(r'<meta name="description"[^>]*>', f'<meta name="description" content="{e(desc)}">\n<link rel="canonical" href="{BASE}{path}">', head)
    header = relink(block(src, '<header class="hdr"', '</header>'), up)
    tail = relink(src[src.index('<div class="tape">'):src.index('<dialog')], up).rstrip()
    css = '../' * (up - 1) + 'legal.css'
    return f'''{head.rstrip()}
<link rel="stylesheet" href="{css}">
</head>
<body>
{header}

<main>
{body}
</main>
{tail}
{JS}
</body>
</html>
'''


def doc_body(title, lead, secs):
    nav = ''.join(f'<a href="#s{i}"><b>{i:02d}</b>{e(h)}</a>' for i, (h, _) in enumerate(secs, 1))
